"""v1.1 milestone (i): M0 (v1.0) vs M1 (two-model sequential test) on decoy scenarios.

    python experiments/run_decoy_benchmark.py            # full: B 1000 seeds, A/C 500
    python experiments/run_decoy_benchmark.py --quick    # CI smoke run

Thresholds are the a-priori +-log 99 of SPRTConfig, NOT tuned on these runs,
so no seed split is needed here. Choosing an operating point on held-out
seeds is milestone (iii) (design doc §6.3).

Writes results/decoys_m1_runs.csv, results/decoys_m1.json, results/decoys_m1.md.
"""

from __future__ import annotations

import argparse
import csv
import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
from scipy.stats import beta

from argus_autonomy import NOMINAL
from argus_autonomy.config import CLASS_NAMES, SPRTConfig
from argus_autonomy.decision import run_decision_mission

ROOT = Path(__file__).resolve().parents[1]

# label -> (method, SPRTConfig)
VARIANTS = {
    # milestone (i) is pinned to its own rules so that this script keeps reproducing it
    "M0": ("M0", SPRTConfig(clear_gate=None)),
    "M1": ("M1", SPRTConfig(omega=None, clear_gate=None)),
    "M1, omega = 0": ("M1", SPRTConfig(omega=0.0, clear_gate=None)),  # ablation of the H0 cue split
}


def _job(args):
    label, family, seed = args
    method, sprt = VARIANTS[label]
    r = run_decision_mission(NOMINAL, method, family, seed, sprt=sprt)
    row = r.summary() | {"variant": label}
    row["llr_peak_abs"] = float(np.max(np.abs(r.llr))) if r.llr else float("nan")
    return row


def cp(k: int, n: int, a: float = 0.05) -> list[float]:
    lo = beta.ppf(a / 2, k, n - k + 1) if k > 0 else 0.0
    hi = beta.ppf(1 - a / 2, k + 1, n - k) if k < n else 1.0
    return [float(lo), float(hi)]


def rate(k: int, n: int) -> dict:
    return {"k": k, "n": n, "p": k / n if n else float("nan"), "ci95": cp(k, n)}


def med_ci(x, rng, b=2000) -> dict:
    x = np.asarray([v for v in x if np.isfinite(v)], float)
    if x.size == 0:
        return {"median": None, "ci95": None, "n": 0}
    boots = np.median(rng.choice(x, size=(b, x.size)), axis=1)
    return {"median": float(np.median(x)), "ci95": [float(np.percentile(boots, 2.5)),
                                                    float(np.percentile(boots, 97.5))], "n": int(x.size)}


def summarise(rows):
    rng = np.random.default_rng(0)
    out = {}
    for label in VARIANTS:
        out[label] = {}
        for fam in ("A", "B", "C"):
            rs = [r for r in rows if r["variant"] == label and r["family"] == fam]
            if not rs:
                continue
            n = len(rs)
            dec = [r["decision"] for r in rs]
            s = {
                "n": n,
                "decisions": {d: dec.count(d) for d in ("ALERT", "CLEAR", "UNDECIDED")},
                "geofence_violations": int(sum(r["geofence_violations"] for r in rs)),
                "returned_to_base": int(sum(bool(r["returned_to_base"]) for r in rs)),
                "min_reserve_ticks": int(min(r["reserve_left"] for r in rs)),
                "llr_peak_abs_median": (float(np.nanmedian([r["llr_peak_abs"] for r in rs]))
                                        if label != "M0" else None),
            }
            if fam == "B":
                s["P_FA"] = rate(dec.count("ALERT"), n)
                s["P_U"] = rate(dec.count("UNDECIDED"), n)
                s["t_clear_min"] = med_ci([r["t_decision_min"] for r in rs if r["decision"] == "CLEAR"], rng)
                s["t_false_alert_min"] = med_ci([r["t_decision_min"] for r in rs if r["decision"] == "ALERT"], rng)
            else:
                ok = [r for r in rs if r["decision"] == "ALERT" and r["alert_correct"]]
                mis = [r for r in rs if r["decision"] == "ALERT" and not r["alert_correct"]]
                s["P_D"] = rate(len(ok), n)
                s["P_MIS"] = rate(len(mis), n)
                s["P_MIS_by_decoy"] = {CLASS_NAMES[k]: sum(r["alert_on_decoy"] == k for r in mis)
                                       for k in range(len(CLASS_NAMES))}
                s["P_CLEAR_on_fire"] = rate(dec.count("CLEAR"), n)
                s["P_U"] = rate(dec.count("UNDECIDED"), n)
                s["t_correct_alert_min"] = med_ci([r["t_decision_min"] for r in ok], rng)
                f1 = np.array([r["f1"] for r in rs])
                s["f1_mean"] = float(f1.mean())
                s["f1_ci95"] = float(1.96 * f1.std(ddof=1) / np.sqrt(n))
                s["f1_mean_after_correct_alert"] = float(np.mean([r["f1"] for r in ok])) if ok else None
            out[label][fam] = s
    return out


def pct(r):
    lo, hi = r["ci95"]
    return f"{100 * r['p']:.1f} % ({r['k']}/{r['n']}; {100 * lo:.1f}–{100 * hi:.1f})"


def mins(m):
    if not m or m["median"] is None:
        return "—"
    return f"{m['median']:.2f} [{m['ci95'][0]:.2f}–{m['ci95'][1]:.2f}]"


def write_md(summary, path):
    L = ["# v1.1 milestone (i): decoy discrimination, M0 vs M1", "",
         ("Generated by `experiments/run_decoy_benchmark.py`. Thresholds fixed a priori at log-odds ±log 99; "
          "not tuned on these runs. Rates: percentage (count; Clopper–Pearson 95 % CI). "
          "Times: median [bootstrap 95 % CI], minutes after launch."), "",
         "## Family B — decoys only, the satellite cue is a decoy", "",
         "| method | false alerts P_FA | undecided | time to CLEAR | time to false alert |",
         "|---|---|---|---|---|"]
    for v, s in summary.items():
        b = s.get("B")
        if b:
            L.append(f"| {v} | {pct(b['P_FA'])} | {pct(b['P_U'])} | {mins(b['t_clear_min'])} | "
                     f"{mins(b['t_false_alert_min'])} |")
    for fam, title in (("A", "Family A — fire plus decoys"), ("C", "Family C — fire only (v1.0 scenario)")):
        L += ["", f"## {title}", "",
              ("| method | correct alert P_D | alert in wrong place P_MIS | CLEAR on a real fire | undecided "
               "| time to correct alert | map F1 at landing |"),
              "|---|---|---|---|---|---|---|"]
        for v, s in summary.items():
            a = s.get(fam)
            if a:
                L.append(f"| {v} | {pct(a['P_D'])} | {pct(a['P_MIS'])} | {pct(a['P_CLEAR_on_fire'])} | "
                         f"{pct(a['P_U'])} | {mins(a['t_correct_alert_min'])} | "
                         f"{a['f1_mean']:.3f} ± {a['f1_ci95']:.3f} |")
    L += ["", "## Safety", "", "| method | family | geofence violations | returned to base | min reserve (ticks) |",
          "|---|---|---|---|---|"]
    for v, s in summary.items():
        for fam, a in s.items():
            L.append(f"| {v} | {fam} | {a['geofence_violations']} | {a['returned_to_base']}/{a['n']} | "
                     f"{a['min_reserve_ticks']} |")
    L += ["", "## Overconfidence of the approximate likelihoods", "",
          ("Median over missions of the peak |log-odds| reached (nats). Values far above the thresholds "
           "(4.6) mean the within-model independence assumption makes the statistic overconfident; "
           "milestone (iii) measures how much (design doc §6.4)."), "",
          "| method | A | B | C |", "|---|---|---|---|"]
    for v, s in summary.items():
        if v != "M0":
            L.append(f"| {v} | " + " | ".join(f"{s[f]['llr_peak_abs_median']:.1f}" for f in "ABC") + " |")
    path.write_text("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--workers", type=int, default=None)
    args = ap.parse_args()
    nb, nac = (20, 10) if args.quick else (1000, 500)
    jobs = [(v, f, s) for v in VARIANTS for f, n in (("B", nb), ("A", nac), ("C", nac)) for s in range(n)]
    with ProcessPoolExecutor(args.workers) as ex:
        rows = list(ex.map(_job, jobs, chunksize=8))
    summary = summarise(rows)
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    suffix = "_quick" if args.quick else ""
    with open(out / f"decoys_m1_runs{suffix}.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (out / f"decoys_m1{suffix}.json").write_text(json.dumps(summary, indent=1))
    write_md(summary, out / f"decoys_m1{suffix}.md")
    print((out / f"decoys_m1{suffix}.md").read_text())


if __name__ == "__main__":
    main()
