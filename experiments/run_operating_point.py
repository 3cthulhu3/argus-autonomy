"""v1.1 milestone (iii): M3 on-line at its chosen operating point, held-out seeds.

    python experiments/run_operating_point.py

Re-flies every held-out mission with the thresholds set (not as a sweep), so the
post-decision phase (mapping after ALERT, return after CLEAR) and the alert
location are those of the deployed rule. Also checks, mission by mission, that the
on-line decision equals the first-passage decision of the sweep log.
Writes results/operating_point.json and .md.
"""

from __future__ import annotations

import json
from concurrent.futures import ProcessPoolExecutor
from dataclasses import replace
from pathlib import Path

import numpy as np
from analyse_sweep import Mission, load
from run_decoy_benchmark import med_ci, pct, rate
from run_sweep import SPLITS, STEER

from argus_autonomy import NOMINAL
from argus_autonomy.config import SPRTConfig
from argus_autonomy.decision import run_decision_mission

ROOT = Path(__file__).resolve().parents[1]
METHOD = "M3"
OP = json.loads((ROOT / "results" / "sweep_select.json").read_text())["operating_points"][METHOD]
SPRT = replace(SPRTConfig(steer_clear=STEER), alert=OP["a"], clear=OP["b"])


def _job(args):
    fam, seed = args
    return run_decision_mission(NOMINAL, METHOD, fam, seed, sprt=SPRT).summary()


def main():
    jobs = [(f, s) for f, seeds in SPLITS["heldout"].items() for s in seeds]
    with ProcessPoolExecutor() as ex:
        rows = list(ex.map(_job, jobs, chunksize=8))
    sweep = {(r["family"], r["seed"]): Mission(r) for r in load("heldout") if r["method"] == METHOD}
    mismatch = [(r["family"], r["seed"]) for r in rows
                if sweep[(r["family"], r["seed"])].decide(OP["a"], OP["b"])[0] != r["decision"]]
    rng = np.random.default_rng(0)
    B = [r for r in rows if r["family"] == "B"]
    F = [r for r in rows if r["family"] != "B"]
    ok = [r for r in F if r["decision"] == "ALERT" and r["alert_correct"]]
    out = {
        "method": METHOD, "a": OP["a"], "b": OP["b"], "steer_clear": STEER,
        "first_passage_mismatches": len(mismatch),
        "P_FA": rate(sum(r["decision"] == "ALERT" for r in B), len(B)),
        "P_U_B": rate(sum(r["decision"] == "UNDECIDED" for r in B), len(B)),
        "t_clear": med_ci([r["t_decision_min"] for r in B if r["decision"] == "CLEAR"], rng),
        "fire_cleared": rate(sum(r["decision"] == "CLEAR" for r in F), len(F)),
        "fire_alert_wrong_place": rate(sum(r["decision"] == "ALERT" and not r["alert_correct"] for r in F), len(F)),
        "P_D": rate(len(ok), len(F)),
        "t_alert": med_ci([r["t_decision_min"] for r in ok], rng),
        "f1_A": float(np.mean([r["f1"] for r in F if r["family"] == "A"])),
        "f1_C": float(np.mean([r["f1"] for r in F if r["family"] == "C"])),
        "geofence_violations": int(sum(r["geofence_violations"] for r in rows)),
        "returned_to_base": int(sum(bool(r["returned_to_base"]) for r in rows)), "n": len(rows),
    }
    L = [f"# v1.1 milestone (iii): {METHOD} at its operating point, held-out seeds, on-line", "",
         ("Generated by `experiments/run_operating_point.py`. B seeds 1000–1999, A and C 500–999. "
          f"Thresholds a = {OP['a']:g}, b = {OP['b']:g} (chosen on selection seeds, `results/sweep_select.json`)."),
         "", "| metric | value |", "|---|---|",
         f"| false alerts on a decoy cue (B) | {pct(out['P_FA'])} |",
         f"| undecided (B) | {pct(out['P_U_B'])} |",
         f"| time to CLEAR (B), median [95 % CI] | {out['t_clear']['median']:.2f} [{out['t_clear']['ci95'][0]:.2f}–{out['t_clear']['ci95'][1]:.2f}] min |",
         f"| correct alert (A ∪ C) | {pct(out['P_D'])} |",
         f"| real fire CLEARed (A ∪ C) | {pct(out['fire_cleared'])} |",
         f"| alert in the wrong place (A ∪ C) | {pct(out['fire_alert_wrong_place'])} |",
         f"| time to correct alert, median [95 % CI] | {out['t_alert']['median']:.2f} [{out['t_alert']['ci95'][0]:.2f}–{out['t_alert']['ci95'][1]:.2f}] min |",
         f"| map F1 at landing, A / C | {out['f1_A']:.3f} / {out['f1_C']:.3f} |",
         f"| geofence violations | {out['geofence_violations']} |",
         f"| returned to base | {out['returned_to_base']}/{out['n']} |",
         f"| on-line decision ≠ first passage of the sweep log | {len(mismatch)} of {len(rows)} |"]
    (ROOT / "results" / "operating_point.json").write_text(json.dumps(out, indent=1))
    (ROOT / "results" / "operating_point.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
