"""Paired tests for the milestone (ii) pre-registered expectations, on identical seeds.

    python experiments/analyse_milestone_ii.py

Reads results/decoys_m2_runs.csv; re-runs a 200-seed sample to measure how
often the Chernoff planner is actually in control.  Writes
results/decoys_m2_tests.md and .json.
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

import numpy as np
from scipy.stats import binomtest, wilcoxon

from argus_autonomy import NOMINAL, decision
from argus_autonomy.planners import Chernoff

ROOT = Path(__file__).resolve().parents[1]


def load():
    with open(ROOT / "results" / "decoys_m2_runs.csv") as fh:
        rows = list(csv.DictReader(fh))
    idx = {}
    for r in rows:
        idx[(r["variant"], r["family"], int(r["seed"]))] = r
    return rows, idx


def mcnemar(idx, a, b, fam, bad, cue=None):
    """Exact McNemar on 'bad' outcomes: seeds where only a errs vs only b errs."""
    seeds = sorted(s for (v, f, s) in idx if v == a and f == fam
                   and (cue is None or idx[(v, f, s)]["cue_decoys"] == cue))
    only_a = sum(idx[(a, fam, s)]["decision"] == bad and idx[(b, fam, s)]["decision"] != bad for s in seeds)
    only_b = sum(idx[(b, fam, s)]["decision"] == bad and idx[(a, fam, s)]["decision"] != bad for s in seeds)
    p = binomtest(only_a, only_a + only_b).pvalue if only_a + only_b else 1.0
    return {"n": len(seeds), "only_" + a: only_a, "only_" + b: only_b, "p": float(p)}


def paired_time(idx, a, b, fam, dec, cue=None):
    """Wilcoxon signed-rank on decision times, seeds where both reached `dec`."""
    seeds = [s for (v, f, s) in idx if v == a and f == fam
             and (cue is None or idx[(v, f, s)]["cue_decoys"] == cue)
             and idx[(a, fam, s)]["decision"] == dec and idx[(b, fam, s)]["decision"] == dec]
    d = np.array([float(idx[(b, fam, s)]["t_decision_min"]) - float(idx[(a, fam, s)]["t_decision_min"])
                  for s in seeds])
    nz = d[d != 0]
    p = float(wilcoxon(nz).pvalue) if nz.size >= 10 else float("nan")
    return {"n": len(seeds), "median_diff_min": float(np.median(d)) if d.size else None,
            "b_faster": int((d < 0).sum()), "a_faster": int((d > 0).sum()), "p": p}


def chernoff_share(method="M2", n=200):
    """Fraction of planning calls in which the Chernoff rule (not the fallback) chose the look."""
    modes = Counter()
    orig = Chernoff.plan

    def spy(self, ctx, test, feasible_close=None):
        out = orig(self, ctx, test, feasible_close)
        modes[self.last_mode] += 1
        return out

    Chernoff.plan = spy
    try:
        for fam in ("A", "B"):
            for s in range(n // 2):
                decision.run_decision_mission(NOMINAL, method, fam, s)
    finally:
        Chernoff.plan = orig
    tot = sum(modes.values())
    return {k: v / tot for k, v in modes.items()} | {"plans": tot}


def main():
    _, idx = load()
    res = {
        "gate: missed fires, A (M1 no gate vs M1)": mcnemar(idx, "M1, no gate (milestone i)", "M1", "A", "CLEAR"),
        "gate: false alerts, B": mcnemar(idx, "M1, no gate (milestone i)", "M1", "B", "ALERT"),
        "gate: time to CLEAR, B": paired_time(idx, "M1, no gate (milestone i)", "M1", "B", "CLEAR"),
        "E3: false alerts, B (M1 vs M2)": mcnemar(idx, "M1", "M2", "B", "ALERT"),
        "E3: missed fires, A (M1 vs M2)": mcnemar(idx, "M1", "M2", "A", "CLEAR"),
        "E3: time to CLEAR, B (M1 vs M2)": paired_time(idx, "M1", "M2", "B", "CLEAR"),
        "E3: time to correct alert, A (M1 vs M2)": paired_time(idx, "M1", "M2", "A", "ALERT"),
        "E4: false alerts, warm-only cue (M2 vs M3)": mcnemar(idx, "M2", "M3", "B", "ALERT", "warm"),
        "E4: time to CLEAR, warm-only cue (M2 vs M3)": paired_time(idx, "M2", "M3", "B", "CLEAR", "warm"),
        "E4: false alerts, hot-only cue (M2 vs M3)": mcnemar(idx, "M2", "M3", "B", "ALERT", "hot"),
        "E4: time to CLEAR, hot-only cue (M2 vs M3)": paired_time(idx, "M2", "M3", "B", "CLEAR", "hot"),
        "E6: false alerts, B (M3 vs M3 phi=0.5)": mcnemar(idx, "M3", "M3, phi = 0.5", "B", "ALERT"),
        "Chernoff in control, M2 (share of planning calls)": chernoff_share("M2"),
        "Chernoff in control, M3 (share of planning calls)": chernoff_share("M3"),
    }
    (ROOT / "results" / "decoys_m2_tests.json").write_text(json.dumps(res, indent=1))
    L = ["# Milestone (ii): paired tests on identical seeds", "",
         ("Generated by `experiments/analyse_milestone_ii.py`. McNemar: exact binomial on discordant seeds. "
          "Times: Wilcoxon signed-rank on seeds where both methods reached the same decision."), ""]
    for k, v in res.items():
        L.append(f"- **{k}**: " + ", ".join(f"{a} = {b:.3g}" if isinstance(b, float) else f"{a} = {b}"
                                              for a, b in v.items()))
    (ROOT / "results" / "decoys_m2_tests.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
