"""v1.1 milestone (iii): re-check, on held-out seeds, the two milestone (i) choices
that were made on benchmark seeds (design doc §10, changes 3 and 4).

    python experiments/recheck_milestone_i.py

  change 3  omega matched to the generator (default) vs omega = 0
  change 4  planner on P(any heat) (default) vs on P(fire)

M1 with the CLEAR gate at the a-priori thresholds, B 1000-1999, A and C 500-999.
Paired on identical seeds; exact McNemar on discordant missions, sign test on F1.
Writes results/recheck_milestone_i.json and .md.
"""

from __future__ import annotations

import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
from run_decoy_benchmark import pct, rate
from run_sweep import SPLITS
from scipy.stats import binomtest

from argus_autonomy import NOMINAL
from argus_autonomy.config import SPRTConfig
from argus_autonomy.decision import run_decision_mission

ROOT = Path(__file__).resolve().parents[1]
VARIANTS = {
    "default": {"sprt": SPRTConfig()},
    "omega = 0": {"sprt": SPRTConfig(omega=0.0)},
    "plan on P(fire)": {"sprt": SPRTConfig(), "plan_on": "fire"},
}


def _job(args):
    v, fam, seed = args
    r = run_decision_mission(NOMINAL, "M1", fam, seed, **VARIANTS[v])
    return {"variant": v} | r.summary()


def p2(k1: int, k2: int) -> float:
    n = k1 + k2
    return 1.0 if n == 0 else float(binomtest(k1, n, 0.5).pvalue)


def main():
    jobs = [(v, f, s) for v in VARIANTS for f, seeds in SPLITS["heldout"].items() for s in seeds]
    with ProcessPoolExecutor() as ex:
        rows = list(ex.map(_job, jobs, chunksize=8))
    by = {(r["variant"], r["family"], r["seed"]): r for r in rows}
    keys = sorted({(f, s) for _, f, s in by})
    out, L = {}, ["# Re-check of milestone (i) choices on held-out seeds", "",
                  ("Generated by `experiments/recheck_milestone_i.py`. M1, CLEAR gate, a = −b = log 99; "
                   "B 1000–1999, A and C 500–999; paired on identical seeds."), "",
                  "| variant | false alerts (B) | real fire CLEARed (A ∪ C) | map F1, A ∪ C (mean) |", "|---|---|---|---|"]
    for v in VARIANTS:
        B = [by[(v, f, s)] for f, s in keys if f == "B"]
        F = [by[(v, f, s)] for f, s in keys if f != "B"]
        out[v] = {"P_FA": rate(sum(r["decision"] == "ALERT" for r in B), len(B)),
                  "fire_cleared": rate(sum(r["decision"] == "CLEAR" for r in F), len(F)),
                  "f1_mean": float(np.mean([r["f1"] for r in F]))}
        L.append(f"| {v} | {pct(out[v]['P_FA'])} | {pct(out[v]['fire_cleared'])} | {out[v]['f1_mean']:.3f} |")
    L += ["", "## Paired against the default", "",
          "| variant | false alerts: default only / variant only (p) | fires CLEARed: default only / variant only (p) | F1: default better / variant better (p) |",
          "|---|---|---|---|"]
    for v in list(VARIANTS)[1:]:
        fa = [(by[("default", f, s)]["decision"] == "ALERT", by[(v, f, s)]["decision"] == "ALERT") for f, s in keys if f == "B"]
        mi = [(by[("default", f, s)]["decision"] == "CLEAR", by[(v, f, s)]["decision"] == "CLEAR") for f, s in keys if f != "B"]
        f1 = [(by[("default", f, s)]["f1"], by[(v, f, s)]["f1"]) for f, s in keys if f != "B"]
        d = {"fa": (sum(a and not b for a, b in fa), sum(b and not a for a, b in fa)),
             "miss": (sum(a and not b for a, b in mi), sum(b and not a for a, b in mi)),
             "f1": (sum(a > b for a, b in f1), sum(b > a for a, b in f1))}
        out[v]["paired"] = {k: {"default_only": x, "variant_only": y, "p": p2(x, y)} for k, (x, y) in d.items()}
        cells = [f"{x} / {y} ({p2(x, y):.2g})" for x, y in d.values()]
        L.append(f"| {v} | " + " | ".join(cells) + " |")
    (ROOT / "results" / "recheck_milestone_i.json").write_text(json.dumps(out, indent=1))
    (ROOT / "results" / "recheck_milestone_i.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
