"""Why does M1 CLEAR a real fire?  Failure analysis of milestone (i).

    python experiments/analyse_decoy_misses.py

Re-runs every M1 mission in families A and C that ended in CLEAR (from
results/decoys_m1_runs.csv) with the sensor instrumented, and counts how many
fire and decoy detections the drone made before the decision.  Writes
results/decoys_m1_misses.md and .json.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

from argus_autonomy import NOMINAL, decision
from argus_autonomy.config import EMPTY, FIRE, HOT, WARM, DecoyConfig

ROOT = Path(__file__).resolve().parents[1]
TICKS_PER_MIN = 60.0 / NOMINAL.dt_s


def instrumented(family: str, seed: int, t_decision_min: float) -> dict:
    log = []
    original = decision.observe_wide

    def spy(classes, pos, theta, radius, rng):
        fp, z = original(classes, pos, theta, radius, rng)
        c = classes[fp]
        log.append((int((z & (c == FIRE)).sum()), int((z & ((c == HOT) | (c == WARM))).sum())))
        return fp, z

    decision.observe_wide = spy
    try:
        decision.run_decision_mission(NOMINAL, "M1", family, seed)
    finally:
        decision.observe_wide = original
    k = round(t_decision_min * TICKS_PER_MIN)
    sc = decision.make_decoy_scenario(NOMINAL, DecoyConfig(), family, seed)
    cue = sc.prior >= NOMINAL.prior.p_ring
    return {
        "family": family, "seed": seed, "t_clear_min": t_decision_min,
        "fire_hits_before_clear": sum(a for a, _ in log[:k]),
        "decoy_hits_before_clear": sum(b for _, b in log[:k]),
        "cue_covers_fire": bool((cue & sc.fire.affected).any()),
        "cue_covers_decoy": bool((cue & (sc.decoys != EMPTY)).any()),
    }


def main() -> None:
    with open(ROOT / "results" / "decoys_m1_runs.csv") as fh:
        rows = list(csv.DictReader(fh))
    misses = [(r["family"], int(r["seed"]), float(r["t_decision_min"])) for r in rows
              if r["variant"] == "M1" and r["family"] in ("A", "C") and r["decision"] == "CLEAR"]
    out = [instrumented(*m) for m in misses]
    (ROOT / "results" / "decoys_m1_misses.json").write_text(json.dumps(out, indent=1))

    L = ["# M1 missed fires: failure analysis", "",
         ("Every M1 mission with a real fire (families A, C) that ended in CLEAR, re-run with the sensor "
          "instrumented. Generated by `experiments/analyse_decoy_misses.py`."), ""]
    for fam in ("A", "C"):
        f = [o for o in out if o["family"] == fam]
        never = [o for o in f if o["fire_hits_before_clear"] == 0]
        L += [f"## Family {fam}: {len(f)} missed fires", "",
              f"- fire never detected before CLEAR: **{len(never)}/{len(f)}**"
              + (f" (of these, the cue also covered a decoy in {sum(o['cue_covers_decoy'] for o in never)})"
                 if never else ""),
              f"- fire detected and still CLEARed: **{len(f) - len(never)}/{len(f)}**",
              f"- satellite cue covered the fire: {sum(o['cue_covers_fire'] for o in f)}/{len(f)}", "",
              "| seed | CLEAR at (min) | fire hits before | decoy hits before | cue covers decoy |",
              "|---|---|---|---|---|"]
        L += [f"| {o['seed']} | {o['t_clear_min']:.2f} | {o['fire_hits_before_clear']} | "
              f"{o['decoy_hits_before_clear']} | {'yes' if o['cue_covers_decoy'] else 'no'} |" for o in f]
        L.append("")
    (ROOT / "results" / "decoys_m1_misses.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
