"""v1.3 screen of the one free parameter of the object-level H1, on seeds 5000+.

    python experiments/screen_v13_pblob.py

obj_p_blob in {0.3, 0.6}; obj_radius = 3 and obj_step = 4 are set by geometry
(the lattice spacing is below the disc diameter, so neighbouring discs overlap).
M3, CLEAR gate, thresholds +-log 99, both satellite geometries.

Rule, fixed before the run: missed fires are too rare to resolve on 600 missions,
so the screen judges the frequent failures only. Keep 0.6 (the a-priori value)
unless 0.3 has fewer undecided plus false-alert missions in BOTH geometries by
at least 2 percentage points of decoy missions.
Writes results/screen_v13_pblob.md.
"""

from __future__ import annotations

from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

from argus_autonomy import NOMINAL
from argus_autonomy.config import VIIRS_PIXEL, SPRTConfig
from argus_autonomy.decision import run_decision_mission

ROOT = Path(__file__).resolve().parents[1]
GEOMS = {"G200": NOMINAL, "G400": VIIRS_PIXEL}
PBLOB = (0.3, 0.6)
SEEDS = {"B": range(5000, 5200), "A": range(5000, 5100), "C": range(5000, 5100)}


def _job(args):
    pb, g, fam, seed = args
    r = run_decision_mission(GEOMS[g], "M3", fam, seed,
                             sprt=SPRTConfig(steer_clear=-4.595, h1_model="object", obj_p_blob=pb))
    return pb, g, fam, r.decision, r.t_decision_min, r.alert_correct


def main():
    jobs = [(pb, g, f, s) for pb in PBLOB for g in GEOMS for f, ss in SEEDS.items() for s in ss]
    with ProcessPoolExecutor() as ex:
        rows = list(ex.map(_job, jobs, chunksize=4))
    L = ["# v1.3 screen: obj_p_blob, seeds 5000+", "",
         "Generated by `experiments/screen_v13_pblob.py`. M3, CLEAR gate, ±log 99. Counts out of 200 decoy (B) and 200 fire (A ∪ C) missions.", "",
         "| p_blob | geometry | false alerts (B) | undecided (B) | fires CLEARed | undecided (fire) | median time to CLEAR | median time to correct alert |",
         "|---|---|---|---|---|---|---|---|"]
    score = {}
    for pb in PBLOB:
        for g in GEOMS:
            rs = [r for r in rows if r[0] == pb and r[1] == g]
            B = [r for r in rs if r[2] == "B"]
            F = [r for r in rs if r[2] != "B"]
            fa = sum(r[3] == "ALERT" for r in B)
            ub = sum(r[3] == "UNDECIDED" for r in B)
            score[(pb, g)] = (fa + ub) / len(B)
            tc = [r[4] for r in B if r[3] == "CLEAR"]
            ta = [r[4] for r in F if r[3] == "ALERT" and r[5]]
            L.append(f"| {pb} | {g} | {fa} | {ub} | {sum(r[3] == 'CLEAR' for r in F)} | "
                     f"{sum(r[3] == 'UNDECIDED' for r in F)} | {np.median(tc) if tc else float('nan'):.2f} | "
                     f"{np.median(ta) if ta else float('nan'):.2f} |")
    switch = all(score[(0.3, g)] <= score[(0.6, g)] - 0.02 for g in GEOMS)
    L += ["", f"Rule: switch to 0.3 only if it is better by >= 2 points in both geometries. Decision: **obj_p_blob = {0.3 if switch else 0.6}**."]
    (ROOT / "results" / "screen_v13_pblob.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
