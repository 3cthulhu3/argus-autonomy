"""v1.2b: clean repeat of the ring-aware CLEAR rules with a corrected selection rule
(docs/design/v1.2-coverage-misses.md, §8). The last test of these rules.

    python experiments/v12b.py select     # corrected rule on the existing v1.2 selection sweep
    python experiments/v12b.py heldout    # chosen rule and C0, fresh seeds, on-line

Selection rule, corrected (fixed before running):
  feasible  P_FA upper 95 % bound <= 2 %; undecided <= 3 % in B and in A u C (a margin below
            the 5 % bound that R0.75 broke on fresh seeds in v1.2)
  then      fewest real fires CLEARed; among the pairs tied at that minimum, the MOST CONSERVATIVE
            clear threshold (most negative b), then fastest correct alert, fastest CLEAR, smaller a.
Variant choice and seeds: see the design doc.
"""

from __future__ import annotations

import argparse
import gzip
import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
from run_decoy_benchmark import med_ci, pct, rate
from run_sweep import GRID
from v12 import GEOMS, ORDER, TARGET, VARIANTS, _online_job, evaluate, p2

ROOT = Path(__file__).resolve().parents[1]
SEL_UNDECIDED = 0.03
HELDOUT = {"B": range(3000, 4000), "A": range(1500, 2000), "C": range(1500, 2000)}
ADOPT = {"undecided": 0.05, "p_fa": 0.02, "t_clear_cost_min": 5.0}


def feasible(e: dict) -> bool:
    return (e["P_FA"]["ci95"][1] <= TARGET and e["P_U_B"]["p"] <= SEL_UNDECIDED
            and e["P_U_fire"]["p"] <= SEL_UNDECIDED)


def pick(evs: list[dict]):
    ok = [e for e in evs if feasible(e)]
    if not ok:
        return None, 0
    m = min(e["fire_cleared"]["k"] for e in ok)
    tied = [e for e in ok if e["fire_cleared"]["k"] == m]
    best = min(tied, key=lambda e: (e["b"], e["t_alert_median"], e["t_clear_median"], e["a"]))
    return best, len(ok)


def cmd_select(args):
    with gzip.open(ROOT / "results" / "v12_sweep.jsonl.gz", "rt") as fh:
        rows = [json.loads(line) for line in fh]
    table, ops = {}, {}
    for v in VARIANTS:
        for g in GEOMS:
            rs = [r for r in rows if r["v"] == v and r["g"] == g]
            evs = [evaluate(rs, ia, ib) for ia in range(len(GRID)) for ib in range(len(GRID))]
            best, n_ok = pick(evs)
            table[(v, g)] = {"n_feasible": n_ok, "chosen": best}
            if best:
                ops[(v, g)] = {"a": best["a"], "b": best["b"]}
    eligible = [v for v in VARIANTS if all((v, g) in ops for g in GEOMS)]

    def key(v):
        miss = sum(table[(v, g)]["chosen"]["fire_cleared"]["k"] for g in GEOMS)
        slow = max(table[(v, g)]["chosen"]["t_clear_median"] for g in GEOMS)
        return (miss, slow, ORDER.index(v))
    chosen = min(eligible, key=key) if eligible else None
    out = {"chosen": chosen, "eligible": eligible, "totals": {v: key(v)[0] for v in eligible},
           "operating_points": {f"{v}|{g}": op for (v, g), op in ops.items()},
           "table": {f"{v}|{g}": d for (v, g), d in table.items()}}
    (ROOT / "results" / "v12b_select.json").write_text(json.dumps(out, indent=1, default=float))
    L = ["# v1.2b selection: corrected selection rule on the v1.2 selection sweep", "",
         ("Generated by `experiments/v12b.py select` following `docs/design/v1.2-coverage-misses.md` §8 "
          "(protocol committed before this run). Feasible: false-alert upper bound ≤ 2 %, undecided ≤ 3 %; "
          "among pairs tied at the fewest missed fires, the most conservative clear threshold."), "",
         "| variant | geometry | feasible pairs | a / b | false alerts (B) | undecided B / A ∪ C | real fire CLEARed (A ∪ C) | median time to correct alert | median time to CLEAR |",
         "|---|---|---|---|---|---|---|---|---|"]
    for v in VARIANTS:
        for g in GEOMS:
            d = table[(v, g)]
            e = d["chosen"]
            if e:
                L.append(f"| {v} | {g} | {d['n_feasible']} | {e['a']:g} / {e['b']:g} | {pct(e['P_FA'])} | "
                         f"{e['P_U_B']['k']} / {e['P_U_fire']['k']} | {pct(e['fire_cleared'])} | "
                         f"{e['t_alert_median']:.2f} | {e['t_clear_median']:.2f} |")
            else:
                L.append(f"| {v} | {g} | 0 | infeasible | | | | | |")
    L += ["", f"Eligible: {', '.join(eligible) or 'none'}. Real fires CLEARed, both geometries: "
          + ", ".join(f"{v} {out['totals'][v]}" for v in eligible) + ".", "",
          f"**Chosen rule: {chosen}.**"]
    (ROOT / "results" / "v12b_select.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def cmd_heldout(args):
    sel = json.loads((ROOT / "results" / "v12b_select.json").read_text())
    chosen = sel["chosen"]
    variants = ["C0"] if chosen in (None, "C0") else ["C0", chosen]
    jobs = []
    for v in variants:
        for g in GEOMS:
            op = sel["operating_points"][f"{v}|{g}"]
            jobs += [(v, g, f, s, op["a"], op["b"]) for f, seeds in HELDOUT.items() for s in seeds]
    with ProcessPoolExecutor(args.workers) as ex:
        rows = list(ex.map(_online_job, jobs, chunksize=8))
    with gzip.open(ROOT / "results" / "v12b_heldout_runs.jsonl.gz", "wt") as fh:
        for r in rows:
            fh.write(json.dumps(r, default=float) + "\n")
    rng = np.random.default_rng(0)
    res = {}
    for v in variants:
        for g in GEOMS:
            rs = [r for r in rows if r["v"] == v and r["g"] == g]
            B = [r for r in rs if r["family"] == "B"]
            F = [r for r in rs if r["family"] != "B"]
            res[f"{v}|{g}"] = {
                **sel["operating_points"][f"{v}|{g}"],
                "P_FA": rate(sum(r["decision"] == "ALERT" for r in B), len(B)),
                "P_U_B": rate(sum(r["decision"] == "UNDECIDED" for r in B), len(B)),
                "fire_cleared": rate(sum(r["decision"] == "CLEAR" for r in F), len(F)),
                "fire_alert_wrong_place": rate(sum(r["decision"] == "ALERT" and not r["alert_correct"] for r in F), len(F)),
                "P_U_fire": rate(sum(r["decision"] == "UNDECIDED" for r in F), len(F)),
                "t_clear": med_ci([r["t_decision_min"] for r in B if r["decision"] == "CLEAR"], rng),
                "t_alert": med_ci([r["t_decision_min"] for r in F if r["decision"] == "ALERT" and r["alert_correct"]], rng),
                "geofence_violations": sum(r["geofence_violations"] for r in rs),
                "returned_to_base": sum(bool(r["returned_to_base"]) for r in rs), "n": len(rs),
            }
    paired, verdict = {}, {}
    if len(variants) == 2:
        by = {(r["v"], r["g"], r["family"], r["seed"]): r for r in rows}
        ks = [(f, s) for f, seeds in HELDOUT.items() for s in seeds]
        for g in GEOMS:
            def ev(fams, d):
                x = sum(by[("C0", g, f, s)]["decision"] == d and by[(chosen, g, f, s)]["decision"] != d for f, s in ks if f in fams)
                y = sum(by[(chosen, g, f, s)]["decision"] == d and by[("C0", g, f, s)]["decision"] != d for f, s in ks if f in fams)
                return {"C0_only": x, "chosen_only": y, "p": p2(x, y)}
            paired[g] = {"fire_cleared": ev("AC", "CLEAR"), "false_alert": ev("B", "ALERT")}
        c, z = (lambda k: res[f"{chosen}|{k}"]), (lambda k: res[f"C0|{k}"])
        tot = {v: sum(res[f"{v}|{g}"]["fire_cleared"]["k"] for g in GEOMS) for v in variants}
        cost = {g: c(g)["t_clear"]["median"] - z(g)["t_clear"]["median"] for g in GEOMS}
        und_ok = all(c(g)["P_U_B"]["p"] <= ADOPT["undecided"] and c(g)["P_U_fire"]["p"] <= ADOPT["undecided"] for g in GEOMS)
        fa_ok = all(c(g)["P_FA"]["p"] <= ADOPT["p_fa"] for g in GEOMS)
        verdict = {
            "E23_undecided_ok": und_ok, "E24_fewer_misses": tot[chosen] < tot["C0"],
            "E25_g400_cost_in_2_6": 2.0 <= cost["G400"] <= 6.0, "totals": tot, "t_clear_cost": cost,
            "adopt": und_ok and fa_ok and tot[chosen] < tot["C0"]
                     and all(cost[g] <= ADOPT["t_clear_cost_min"] for g in GEOMS),
        }
    out = {"chosen": chosen, "results": res, "paired": paired, "verdict": verdict}
    (ROOT / "results" / "v12b_heldout.json").write_text(json.dumps(out, indent=1, default=float))

    def mm(m):
        return "—" if m["median"] is None else f"{m['median']:.2f} [{m['ci95'][0]:.2f}–{m['ci95'][1]:.2f}]"
    L = ["# v1.2b held-out: chosen rule against C0, fresh seeds", "",
         ("Generated by `experiments/v12b.py heldout`. Seeds never flown before (B 3000–3999, A and C 1500–1999), "
          "on-line, each variant at its own per-geometry operating point from `results/v12b_select.json`."), "",
         "| variant | geometry | a / b | false alerts (B) | undecided B / A ∪ C | real fire CLEARed (A ∪ C) | alert in wrong place | time to correct alert | time to CLEAR (B) | geofence / RTB |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in res.items():
        vv, g = k.split("|")
        L.append(f"| {vv} | {g} | {r['a']:g} / {r['b']:g} | {pct(r['P_FA'])} | {r['P_U_B']['k']} / {r['P_U_fire']['k']} | "
                 f"{pct(r['fire_cleared'])} | {r['fire_alert_wrong_place']['k']} | {mm(r['t_alert'])} | {mm(r['t_clear'])} | "
                 f"{r['geofence_violations']} / {r['returned_to_base']} of {r['n']} |")
    for g, p in paired.items():
        L.append(f"\nPaired, {g}: fires CLEARed C0 only {p['fire_cleared']['C0_only']}, {chosen} only "
                 f"{p['fire_cleared']['chosen_only']} (exact McNemar p = {p['fire_cleared']['p']:.2g}); false alerts "
                 f"C0 only {p['false_alert']['C0_only']}, {chosen} only {p['false_alert']['chosen_only']}.")
    if verdict:
        L += ["", "## Pre-registered expectations and adoption", "",
              f"- E23 undecided ≤ 5 % for the chosen rule in both geometries: {'met' if verdict['E23_undecided_ok'] else 'not met'}",
              f"- E24 fewer real fires CLEARed than C0 (both geometries): {'met' if verdict['E24_fewer_misses'] else 'not met'} "
              f"({verdict['totals']})",
              f"- E25 time-to-CLEAR cost at 400 m between +2 and +6 min: {'met' if verdict['E25_g400_cost_in_2_6'] else 'not met'} "
              f"({verdict['t_clear_cost']['G400']:+.2f} min; 200 m: {verdict['t_clear_cost']['G200']:+.2f} min)",
              f"- **Adoption criterion: {'ADOPT' if verdict['adopt'] else 'DO NOT ADOPT'}**"]
    (ROOT / "results" / "v12b_heldout.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("select", "heldout"))
    ap.add_argument("--workers", type=int, default=None)
    args = ap.parse_args()
    {"select": cmd_select, "heldout": cmd_heldout}[args.cmd](args)


if __name__ == "__main__":
    main()
